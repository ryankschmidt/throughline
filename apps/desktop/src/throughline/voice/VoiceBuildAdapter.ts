// @effect-diagnostics nodeBuiltinImport:off -- Native build/resource adapter; private compiler and staged filesystem only.
import * as NodeChildProcess from "node:child_process";
import * as NodeFSP from "node:fs/promises";
import * as NodePath from "node:path";
import * as NodeModule from "node:module";
import { build } from "vite-plus";
import { VOICE_NATIVE_RESOURCE, VOICE_PRELOAD_RESOURCE } from "./VoiceBridgeContract.ts";

export const VOICE_USAGE_DESCRIPTIONS = {
  NSMicrophoneUsageDescription:
    "ThroughLine records your voice when you use dictation and transcribes it on this Mac.",
  NSSpeechRecognitionUsageDescription:
    "ThroughLine uses Apple Speech on this Mac to turn dictation into editable text.",
} as const;
export const MAC_VOICE_EXTRA_RESOURCES = [
  { from: `apps/desktop/prod-resources/${VOICE_NATIVE_RESOURCE}`, to: VOICE_NATIVE_RESOURCE },
  { from: `apps/desktop/prod-resources/${VOICE_PRELOAD_RESOURCE}`, to: VOICE_PRELOAD_RESOURCE },
] as const;

/** Only the controlled flat root dictionaries generated by our builder and
 * its pinned Electron template. Never a general or renderer-supplied parser.
 */
export function addAudioToGeneratedEntitlements(xml: string): string {
  const key = "<key>com.apple.security.device.audio-input</key>";
  if (
    (xml.match(/<dict>/g) ?? []).length !== 1 ||
    !/<plist\b[^>]*>\s*<dict>/.test(xml) ||
    !/<\/dict>\s*<\/plist>\s*$/.test(xml)
  )
    throw new Error("Unsupported generated entitlement dictionary");
  const existing = xml.split(key).length - 1;
  if (existing > 1) throw new Error("Duplicate generated audio entitlement");
  if (existing === 1) {
    const pattern = /<key>com\.apple\.security\.device\.audio-input<\/key>\s*<(true|false)\s*\/>/;
    if (!pattern.test(xml)) throw new Error("Generated audio entitlement is not boolean");
    return xml.replace(pattern, `${key}<true/>`);
  }
  return xml.replace(/<\/dict>\s*<\/plist>\s*$/, `${key}<true/>\n</dict>\n</plist>\n`);
}

const exec = (file: string, args: readonly string[]) =>
  new Promise<void>((resolve, reject) => {
    NodeChildProcess.execFile(
      file,
      [...args],
      { maxBuffer: 1024 * 1024, env: { PATH: "/usr/bin:/bin", LANG: "en_US.UTF-8" } },
      (error) => (error ? reject(error) : resolve()),
    );
  });

/** Called only by the existing artifact builder; never an install or PATH command. */
export async function stageDesktopVoice(input: {
  readonly hostPlatform: string;
  readonly repoRoot: string;
  readonly stageResourcesDir: string;
  readonly arch: "arm64" | "x64" | "universal";
  readonly appId: string;
  readonly version: string;
}): Promise<void> {
  if (input.hostPlatform !== "darwin") throw new Error("Mac voice artifacts must build on the Mac");
  const source = NodePath.join(input.repoRoot, "apps/desktop/src/throughline/voice");
  const info = NodePath.join(input.stageResourcesDir, "voice-native-info.plist");
  const escape = (value: string) =>
    value
      .replaceAll("&", "&amp;")
      .replaceAll("<", "&lt;")
      .replaceAll(">", "&gt;")
      .replaceAll('"', "&quot;");
  await NodeFSP.writeFile(
    info,
    `<?xml version="1.0" encoding="UTF-8"?><!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd"><plist version="1.0"><dict>
<key>CFBundleIdentifier</key><string>${escape(input.appId)}.voice</string>
<key>CFBundleExecutable</key><string>${VOICE_NATIVE_RESOURCE}</string>
<key>CFBundleName</key><string>ThroughLine Voice</string>
<key>CFBundleVersion</key><string>${escape(input.version)}</string>
<key>NSMicrophoneUsageDescription</key><string>${escape(VOICE_USAGE_DESCRIPTIONS.NSMicrophoneUsageDescription)}</string>
<key>NSSpeechRecognitionUsageDescription</key><string>${escape(VOICE_USAGE_DESCRIPTIONS.NSSpeechRecognitionUsageDescription)}</string>
</dict></plist>`,
  );
  const output = NodePath.join(input.stageResourcesDir, VOICE_NATIVE_RESOURCE);
  // Preserve the installed builder's entitlement template as opaque bytes,
  // rather than duplicating its JIT/library policy. Its measured per-file
  // selector consumes these existing resource names for parent/helpers.
  const consumer = NodeModule.createRequire(
    NodePath.join(input.repoRoot, "apps/desktop/package.json"),
  );
  const builder = NodeModule.createRequire(consumer.resolve("electron-builder"));
  const template = NodePath.resolve(
    NodePath.dirname(builder.resolve("app-builder-lib")),
    "../templates/entitlements.mac.plist",
  );
  for (const name of ["entitlements.mac.plist", "entitlements.mac.inherit.plist"]) {
    const destination = NodePath.join(input.stageResourcesDir, name);
    let xml: string;
    try {
      xml = await NodeFSP.readFile(destination, "utf8");
    } catch (error) {
      if (!(error instanceof Error) || !("code" in error) || error.code !== "ENOENT") throw error;
      xml = await NodeFSP.readFile(template, "utf8");
    }
    await NodeFSP.writeFile(destination, addAudioToGeneratedEntitlements(xml));
  }
  const architectures = input.arch === "universal" ? (["arm64", "x64"] as const) : [input.arch];
  const slices: string[] = [];
  for (const arch of architectures) {
    const slice = architectures.length === 1 ? output : `${output}.${arch}`;
    await exec("/usr/bin/xcrun", [
      "swiftc",
      "-parse-as-library",
      "-O",
      "-target",
      `${arch === "x64" ? "x86_64" : "arm64"}-apple-macos12.0`,
      NodePath.join(source, "native/AppleSpeech.swift"),
      NodePath.join(source, "native/AppleSpeechCapture.swift"),
      "-Xlinker",
      "-sectcreate",
      "-Xlinker",
      "__TEXT",
      "-Xlinker",
      "__info_plist",
      "-Xlinker",
      info,
      "-o",
      slice,
    ]);
    slices.push(slice);
  }
  if (slices.length > 1) {
    await exec("/usr/bin/lipo", ["-create", ...slices, "-output", output]);
    for (const slice of slices) await NodeFSP.unlink(slice);
  }
  await NodeFSP.chmod(output, 0o755);
  const nativeEntitlements = NodePath.join(
    input.stageResourcesDir,
    "voice-native-entitlements.plist",
  );
  await NodeFSP.writeFile(
    nativeEntitlements,
    '<?xml version="1.0"?><plist version="1.0"><dict><key>com.apple.security.device.audio-input</key><true/></dict></plist>',
  );
  // Ad-hoc fixture/dev identity only; the unchanged owning signer handles the
  // real app identity during its existing signed-build lane.
  await exec("/usr/bin/codesign", [
    "--force",
    "--sign",
    "-",
    "--options",
    "runtime",
    "--entitlements",
    nativeEntitlements,
    output,
  ]);
  await build({
    configFile: false,
    envDir: false,
    build: {
      outDir: input.stageResourcesDir,
      emptyOutDir: false,
      lib: {
        entry: NodePath.join(source, "VoicePreload.cts"),
        formats: ["cjs"],
        fileName: () => VOICE_PRELOAD_RESOURCE,
      },
      rollupOptions: { external: ["electron"] },
    },
  });
}
